/**
 * Normalizes and translates dynamic data strings
 */
export const formatBilingualText = (text, lang = "en", type = "generic") => {
  if (!text || typeof text !== "string") return text || "";
  const clean = text.trim().toLowerCase().replace(/\s+/g, " ");

  // 1. Check Specific Maps
  if (type === "crop" && CROP_TRANS[clean]) return CROP_TRANS[clean][lang];
  if (type === "state" && STATE_TRANS[clean]) return STATE_TRANS[clean][lang];
  if (type === "category" && CAT_TRANS[clean]) return CAT_TRANS[clean][lang];
  if (type === "city" && CITY_TRANS[clean]) return CITY_TRANS[clean][lang];
  if (type === "weather" && WEATHER_TRANS[clean]) return WEATHER_TRANS[clean][lang];
  if (type === "grade" && GRADE_TRANS[clean]) return GRADE_TRANS[clean][lang];

  // Fallback checks
  if (STATE_TRANS[clean]) return STATE_TRANS[clean][lang];
  if (CAT_TRANS[clean]) return CAT_TRANS[clean][lang];
  if (CROP_TRANS[clean]) return CROP_TRANS[clean][lang];
  if (CITY_TRANS[clean]) return CITY_TRANS[clean][lang];
  if (GRADE_TRANS[clean]) return GRADE_TRANS[clean][lang];

  // 2. Handle comma-separated strings (e.g. "Kamrup, Assam")
  if (clean.includes(",")) {
    return clean.split(",").map(part => formatBilingualText(part, lang, type)).join(", ");
  }

  // 3. Normalize Keywords in string (e.g. "narela mandi" -> "Narela Mandi" / "नरेला मंडी")
  // We split the ORIGINAL text to preserve casing for unmapped words
  const delimiterRegex = /([\s/.,()–-]+)/;
  const words = text.split(delimiterRegex);

  const translated = words.map((word) => {
    // If it's a delimiter, keep it
    if (delimiterRegex.test(word)) return word;

    const wordClean = word.toLowerCase();

    // Handle specific dictionaries for words (Towns, States, Crops)
    if (KEYWORD_TRANS[wordClean]) return KEYWORD_TRANS[wordClean][lang];
    if (CITY_TRANS[wordClean]) return CITY_TRANS[wordClean][lang];
    if (STATE_TRANS[wordClean]) return STATE_TRANS[wordClean][lang];
    if (CROP_TRANS[wordClean]) return CROP_TRANS[wordClean][lang];
    
    if (wordClean === "apmc") return lang === "en" ? "APMC" : "एपीएमसी";
    if (wordClean === "wb") return lang === "en" ? "West Bengal" : "पश्चिम बंगाल";
    
    // If no match found:
    if (lang === "en") return word; // Return original word with its original casing
    
    // Hindi Mode Fallback: Capitalize English word for professional look
    return word.charAt(0).toUpperCase() + word.slice(1).toLowerCase();
  });

  return translated.join("");
};
